#!/usr/bin/env python3
"""Build Lily Leap for sharing and for installing on a phone.

From the game source (index.html) this makes:

  lily-leap/LilyLeap.html   one self-contained file (fonts embedded) to send to people
  docs/                     the installable home-screen app, ready for GitHub Pages:
                              index.html, manifest.webmanifest, sw.js (offline play), icons

    python3 lily-leap/build_standalone.py
"""
import base64
import hashlib
import json
import pathlib
import re
import shutil

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "index.html"
OUT = HERE / "LilyLeap.html"
DOCS = HERE.parent / "docs"
ICONS = HERE / "icons"


def font_face(family, path, weight):
    data = base64.b64encode((HERE / "fonts" / path).read_bytes()).decode()
    return (
        f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};"
        f"font-display:swap;src:url(data:font/woff2;base64,{data}) format('woff2')}}"
    )


src = SRC.read_text(encoding="utf-8")

# Drop the Google Fonts links; the fonts get embedded below instead.
src = re.sub(r'<link rel="(preconnect|stylesheet)" href="https://fonts\.[^"]*"[^>]*>\n?', "", src)

title_match = re.match(r"\s*(<title>.*?</title>)\n?", src)
title = title_match.group(1)
body = src[title_match.end():]

# Split the leading <style> into <head>; everything else goes in <body>.
style_end = body.index("</style>") + len("</style>")
style, rest = body[:style_end], body[style_end:].lstrip("\n")

fonts = "<style>\n" + "\n".join([
    font_face("Chewy", "Chewy-latin.woff2", "400"),
    font_face("Nunito", "Nunito-latin.woff2", "700 900"),
]) + "\n</style>"

# Message previews (e.g. tapping the file in iMessage) often show HTML without running scripts.
# Without this, people would see the title card with a "Hop in" button that does nothing.
noscript = """<noscript>
<div class="overlay" style="z-index:50">
  <div class="card">
    <h2>Almost there!</h2>
    <p class="tag">This preview can't run games. Open the file in a web browser to play Lily Leap.</p>
    <p class="small">On a computer: double-click the file. On a phone: ask whoever sent it for the web link.</p>
  </div>
</div>
</noscript>
"""

META = """<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Lily Leap">
<meta name="theme-color" content="#1f5d73">
<meta name="description" content="Hop across the blooms and snap up every fly in the pond.">"""


def document(extra_head="", extra_body=""):
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
{META}
{extra_head}{title}
{fonts}
{style}
</head>
<body>
{noscript}{rest}{extra_body}</body>
</html>
"""


# 1. The single file to send to people.
OUT.write_text(document(), encoding="utf-8")
print(f"Wrote {OUT.relative_to(HERE.parent)} ({OUT.stat().st_size / 1024:.0f} KB)")

# 2. The installable home-screen app (GitHub Pages serves the docs/ folder).
pwa_head = """<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icon-180.png">
<link rel="icon" type="image/png" sizes="192x192" href="icon-192.png">
"""
pwa_body = """<script>
// Offline play: cache the game the first time it loads.
if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost')) {
  window.addEventListener('load', () => { navigator.serviceWorker.register('sw.js').catch(() => {}); });
}
</script>
"""
app_html = document(pwa_head, pwa_body)
DOCS.mkdir(exist_ok=True)
(DOCS / "index.html").write_text(app_html, encoding="utf-8")
for size in (180, 192, 512):
    shutil.copyfile(ICONS / f"icon-{size}.png", DOCS / f"icon-{size}.png")

manifest = {
    "name": "Lily Leap",
    "short_name": "Lily Leap",
    "description": "Hop across the blooms and snap up every fly in the pond.",
    "start_url": "./",
    "scope": "./",
    "display": "fullscreen",
    "orientation": "landscape",
    "background_color": "#1f5d73",
    "theme_color": "#1f5d73",
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}
(DOCS / "manifest.webmanifest").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

# The cache name changes whenever the game changes, so installed copies pick up updates.
version = hashlib.sha256(app_html.encode()).hexdigest()[:12]
sw = f"""// Lily Leap offline cache. Generated by lily-leap/build_standalone.py; do not edit by hand.
const CACHE = 'lilyleap-{version}';
const FILES = ['./', './index.html', './manifest.webmanifest', './icon-180.png', './icon-192.png', './icon-512.png'];

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('lilyleap-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

// Serve from the cache so the game starts instantly and works offline; refresh the cache in the background.
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async cache => {{
    const cached = await cache.match(req, {{ ignoreSearch: true }});
    const network = fetch(req).then(res => {{ if (res.ok) cache.put(req, res.clone()); return res; }}).catch(() => cached);
    return cached || network;
  }}));
}});
"""
(DOCS / "sw.js").write_text(sw, encoding="utf-8")
(DOCS / ".nojekyll").write_text("", encoding="utf-8")
print(f"Wrote docs/ (home-screen app, cache {version})")
